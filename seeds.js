/**
 * THE SEED BANK
 * =========================================================================
 * Short scraps of raw material dealt privately to each player during the
 * writing phase. They are NOT answers — they're kindling.
 *
 * WHY THIS EXISTS
 *   A blank text box freezes people. Not everyone is a natural writer, and in
 *   round one nobody is warmed up yet. Left alone, the two funniest people in
 *   the room take every vote and everyone else quietly checks out. Seeds give
 *   the stuck player a place to push off from.
 *
 * WHY THEY'RE DELIBERATELY GENERIC
 *   These are never matched to the prompt, and that's the point. The comedy in
 *   Cards Against Humanity comes from a mundane card colliding with an absurd
 *   prompt. "Expired mayonnaise" isn't funny; "Cause of death: expired
 *   mayonnaise" is. Prompt-matched seeds would kill the collision.
 *
 * WHAT MAKES A GOOD ONE
 *   1. CONCRETE, NOT ABSTRACT. "A moist handshake" beats "something gross."
 *      Specific things are funny; categories are not.
 *   2. SHORT. It's scanned under a 60-second clock. One to four words.
 *   3. LOADED BUT UNFINISHED. It should suggest a joke without being one, so
 *      the player still supplies the punchline and it stays their answer.
 *   4. MUNDANE MADE SINISTER, OR GRAND MADE PETTY. That's the whole engine.
 *
 * Add your own freely. Same rules as prompts.js: one per line, double quotes,
 * trailing comma. Seeds naming people in your actual room are lethal.
 * =========================================================================
 */

